import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
page.on('console', (m) => { if (m.type() === 'error') console.log('console', m.type(), m.text().slice(0, 200)) })
await page.goto('http://localhost:5173/izvjestaj?lat=45.288186&lon=18.805681&adresa=Bana%20Jela%C4%8Di%C4%87a%201%2C%20Vinkovci')
await page.waitForTimeout(6000)
const map = page.locator('.map')
await map.scrollIntoViewIfNeeded()
await page.waitForTimeout(4000)
await page.locator('.map-wrap').screenshot({ path: process.argv[2] })
await page.locator('[data-category="flood"]').screenshot({ path: process.argv[3] })
await browser.close()
